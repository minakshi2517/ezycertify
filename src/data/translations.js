export function getTranslation(langCode) {
  if (translations[langCode]) return translations[langCode]
  if (langCode.startsWith('en')) return translations['en-US']
  if (langCode.startsWith('hi') || langCode === 'bn' || langCode === 'ta') return translations['hi']
  if (langCode.startsWith('ar') || langCode === 'fa' || langCode === 'ur') return translations['ar']
  return translations['en-US']
}
