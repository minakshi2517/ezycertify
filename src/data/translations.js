export function translateText(text, langCode) {
  if (!text) return ''
  if (!langCode || langCode === 'en-US') return text
  const baseCode = langCode.split('-')[0]
  if (contentTranslations[text]) {
    const dict = contentTranslations[text]
    if (dict[langCode]) return dict[langCode]
    if (dict[baseCode]) return dict[baseCode]
  }
  return text
}
